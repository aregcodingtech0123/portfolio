/**
 * The site's absolute URLs. Every canonical, hreflang, Open Graph, sitemap
 * and JSON-LD URL is built from NEXT_PUBLIC_SITE_URL (validated as https and
 * not localhost in a production build, src/lib/env-validation.ts), never from
 * the request host, so a preview alias or the www/apex twin cannot leak into
 * them. It is a NEXT_PUBLIC_ value, so it is fixed at build time.
 */
import { routing } from "@/i18n/routing";

export type SiteLocale = (typeof routing.locales)[number];

const LOCAL_FALLBACK = "http://localhost:3000";

/**
 * The site origin. Unset and blank both fall back to localhost (`??` alone
 * would hand `new URL` an empty string and throw); production builds never
 * get here without a valid value.
 */
export function siteUrl(env: string | undefined = process.env.NEXT_PUBLIC_SITE_URL): URL {
  return new URL(env?.trim() || LOCAL_FALLBACK);
}

/** Absolute URL for a site path, e.g. absoluteUrl("/en") -> "https://host/en". */
export function absoluteUrl(path: string, base: URL = siteUrl()): string {
  return new URL(path, base).toString();
}

/** Open Graph locale per route locale. */
export const OG_LOCALE: Record<SiteLocale, string> = { en: "en_US", tr: "tr_TR" };

/**
 * hreflang alternates for the home page: one per locale plus x-default on the
 * bare root, which redirects by Accept-Language (src/proxy.ts). This is the
 * only hreflang source; next-intl's Link header is off (alternateLinks: false
 * in src/i18n/routing.ts).
 */
export function homeLanguageAlternates(): Record<SiteLocale | "x-default", string> {
  const languages = Object.fromEntries(
    routing.locales.map((locale) => [locale, `/${locale}`]),
  ) as Record<SiteLocale, string>;
  return { ...languages, "x-default": "/" };
}

